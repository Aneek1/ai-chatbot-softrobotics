"""Generate docs/error-analysis.md from the result files (spec section 11.3).

Usage:
    PYTHONUTF8=1 uv run python -m eval.error_analysis

The examples are the ones the evaluation recorded while it ran: misclassified lines from
eval/langid_eval.py and cited sentences the faithfulness judge called unsupported.
"""

import argparse
import json
from pathlib import Path

from backend.pipeline.languages import display_name, group_of
from training.results_table import latest

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULTS_DIR = REPO_ROOT / "results"
OUTPUT = REPO_ROOT / "docs" / "error-analysis.md"
DEFAULT_DETECTOR = "two-stage+specialist-e5-finetune"
PER_PAIR = 2
MAX_CITATION_EXAMPLES = 10
TEXT_CHARS = 200

GROUP_REASONS = {
    "malay_indonesian": "Malay and Indonesian share most of their vocabulary, "
    "so a sentence with no distinguishing word can go either way",
    "han": "the two Chinese variants share most characters, "
    "so only the characters that differ carry the answer",
    "romanized_hindi": "romanized Hindi, Urdu and English use the same letters, "
    "and short romanized text has little else to go on",
}


def explain(mistake: dict) -> str:
    gold_group = group_of(mistake["gold"])
    group = gold_group if gold_group == group_of(mistake["predicted"]) else None
    reason = GROUP_REASONS.get(group, "the two languages are not in the same confusion group")
    if mistake["slice"] == "1-3 words":
        return f"one to three words: too little text to decide, and {reason}"
    if mistake["slice"] == "code-mixed":
        return f"two languages in one line, labelled with the one contributing more characters; {reason}"
    if mistake["slice"] == "taiwan-vocabulary":
        return f"Taiwan vocabulary converted from Simplified text; {reason}"
    return reason[0].upper() + reason[1:]


def language_section(evaluation: dict, detector: str, source: str) -> list[str]:
    mistakes = evaluation["detectors"][detector]["mistakes"]
    seen: dict[tuple[str, str], int] = {}
    lines = [
        "## Language identification",
        "",
        f"Source: `{source}`, detector `{detector}`. These are lines it got wrong, "
        f"up to {PER_PAIR} per pair of languages.",
        "",
    ]
    for mistake in mistakes:
        pair = (mistake["gold"], mistake["predicted"])
        seen[pair] = seen.get(pair, 0) + 1
        if seen[pair] > PER_PAIR:
            continue
        lines += [
            f"- `{mistake['gold']}` ({display_name(mistake['gold'])}) read as "
            f"`{mistake['predicted']}` ({display_name(mistake['predicted'])}) "
            f"at probability {mistake['probability']}, in the {mistake['slice']} slice of "
            f"{mistake['set']}.",
            f"  - Text: {mistake['text'][:TEXT_CHARS]}",
            f"  - Why: {explain(mistake)}",
        ]
    return lines + [""]


def citation_section(rag: dict, source: str) -> list[str]:
    judged = rag["judged"]
    unsupported = [record for record in judged if record["verdict"] == "unsupported"]
    lines = [
        "## Citations that the cited source does not support",
        "",
        f"Source: `{source}`. Of {len(judged)} cited sentences, `{rag['judge']}` judged "
        f"{len(unsupported)} of {len(judged)} unsupported by the chunk they cite. The app's own "
        "citation check passes all of these: it only tests that the number points at a source that "
        "was provided.",
        "",
    ]
    for record in unsupported[:MAX_CITATION_EXAMPLES]:
        lines += [
            f"- {record['question_id']} cited `{record['chunk_id']}`.",
            f"  - Sentence: {record['sentence'][:TEXT_CHARS]}",
            f"  - Cited chunk: {record['chunk_text'][:TEXT_CHARS]}",
        ]
    return lines + [""]


def render(
    evaluation: tuple[dict, str] | None,
    rag: tuple[dict, str] | None,
    detector: str = DEFAULT_DETECTOR,
) -> str:
    lines = [
        "# Error analysis",
        "",
        "Generated by `eval/error_analysis.py` from the files in `results/`; do not edit by hand.",
        "",
    ]
    if evaluation:
        lines += language_section(evaluation[0], detector, evaluation[1])
    if rag:
        lines += citation_section(rag[0], rag[1])
    if not evaluation and not rag:
        lines += ["No results file was found in `results/`; run the evaluations first.", ""]
    return "\n".join(lines)


def _load(pattern: str) -> tuple[dict, str] | None:
    path = latest(pattern, RESULTS_DIR)
    return (json.loads(path.read_text(encoding="utf-8")), f"results/{path.name}") if path else None


def _write(text: str, path: Path = OUTPUT) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--detector", default=DEFAULT_DETECTOR)
    args = parser.parse_args()
    _write(render(_load("langid-eval-*.json"), _load("rag-eval-*.json"), detector=args.detector))
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
