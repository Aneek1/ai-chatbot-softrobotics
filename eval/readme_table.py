"""Generate the results block in README.md from the committed result files (spec sections 11, 14).

Usage:
    PYTHONUTF8=1 uv run python -m eval.readme_table

Every number in the README comes from here, so none of them is typed by hand. The block is written
between two markers; the text around them is left alone.
"""

import argparse
import json
from pathlib import Path

from backend.pipeline.languages import SUPPORTED
from training.metrics import OUTSIDE
from training.results_table import fmt, latest

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULTS_DIR = REPO_ROOT / "results"
README = REPO_ROOT / "README.md"
START = "<!-- results:start (generated by eval/readme_table.py; do not edit by hand) -->"
END = "<!-- results:end -->"
DEFAULT_DETECTOR = "two-stage+specialist-e5-finetune"
LANGUAGE_SLICES = (
    ("flores200-devtest/sentence", "FLORES sentence"),
    ("flores200-devtest/taiwan-vocabulary", "Taiwan vocabulary"),
    ("dakshina-test/sentence", "Dakshina sentence"),
)


def scores_for(entry: dict, slice_key: str, label: str) -> dict | None:
    scores = entry["slices"].get(slice_key, {}).get("per_label", {}).get(label)
    return scores if scores and scores["support"] else None


def language_table(entry: dict) -> list[str]:
    lines = [
        "| Language | Label | " + " | ".join(title for _, title in LANGUAGE_SLICES) + " |",
        "|---|---|" + "---:|" * len(LANGUAGE_SLICES),
    ]
    for label, name in SUPPORTED.items():
        cells = []
        for key, _ in LANGUAGE_SLICES:
            scores = scores_for(entry, key, label)
            cells.append(fmt(scores["f1"]) if scores else "n/a")
        lines.append(f"| {name} | `{label}` | " + " | ".join(cells) + " |")
    return lines


def confusion_tables(entry: dict, slice_key: str = "flores200-devtest/sentence") -> list[str]:
    lines: list[str] = []
    for group, matrix in entry["slices"][slice_key]["confusions"].items():
        columns = list(next(iter(matrix.values())))
        header = " | ".join(column if column == OUTSIDE else f"`{column}`" for column in columns)
        lines += [
            f"{group}:",
            "",
            f"| Gold, predicted right | {header} |",
            "|---|" + "---:|" * len(columns),
        ]
        for gold, row in matrix.items():
            lines.append(f"| `{gold}` | " + " | ".join(str(row[column]) for column in columns) + " |")
        lines.append("")
    return lines


def threshold_table(entry: dict) -> list[str]:
    lines = ["| Confidence threshold | Coverage | Accuracy |", "|---:|---:|---:|"]
    for row in entry["threshold_sweep"]:
        lines.append(f"| {row['threshold']} | {fmt(row['coverage'])} | {fmt(row['accuracy'])} |")
    return lines


def rag_tables(rag: dict, source: str) -> list[str]:
    lines = [
        f"Source: `{source}`. Answers from `{rag['answer_model']}` over the local index, web search "
        "off. Retrieval counts a hit when a retrieved chunk comes from the question's topic article "
        "in any language.",
        "",
        "| Language | Label | Questions | hit@5 | Answer in the right language | Citations all valid "
        "| Cited chunk supports the sentence |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for label, row in rag["per_language"].items():
        supported = rag["faithfulness_by_language"].get(label, {}).get("supported_rate")
        lines.append(
            f"| {SUPPORTED.get(label, label)} | `{label}` | {row['questions']} | "
            f"{fmt(row['hit_at_5'])} | {fmt(row['answer_language_correct'])} | "
            f"{fmt(row['citations_all_valid'])} | {fmt(supported)} |"
        )
    overall, faithful = rag["overall"], rag["faithfulness"] or {}
    lines.append(
        f"| All languages | | {overall['questions']} | {fmt(overall['hit_at_5'])} | "
        f"{fmt(overall['answer_language_correct'])} | {fmt(overall['citations_all_valid'])} | "
        f"{fmt(faithful.get('supported_rate'))} |"
    )
    lines.append("")
    if faithful:
        lines.append(
            f"\"Citations all valid\" only means every [n] points at a source that was provided. "
            f"The last column is different: a model read each of the {faithful['pairs']} cited "
            f"sentences next to the chunk it cites and judged {faithful['supported']} supported, "
            f"{faithful['unsupported']} unsupported and {faithful['unclear']} unclear."
        )
        agreement = rag.get("judge_agreement")
        if agreement:
            lines.append(
                f"That judge was `{rag['judge']}`, and it agreed with the person on "
                f"{fmt(agreement['agreement'])} of {agreement['labelled']} hand-labelled pairs "
                f"(the judge called {fmt(agreement['judge_supported_rate'])} of them supported, "
                f"the person {fmt(agreement['human_supported_rate'])})."
            )
        lines.append("")
    return lines + [f"- {note}" for note in rag["notes"]] + [""]


def render(
    evaluation: tuple[dict, str] | None,
    rag: tuple[dict, str] | None,
    detector: str = DEFAULT_DETECTOR,
) -> str:
    lines: list[str] = []
    if evaluation:
        results, source = evaluation
        entry = results["detectors"][detector]
        lines += [
            "### Language identification",
            "",
            f"Source: `{source}`, detector `{detector}`, "
            f"{entry['model_bytes'] / 1e6:.1f} MB of model files, "
            f"{fmt(entry['latency']['p50_ms'], 2)} ms per question at the median and "
            f"{fmt(entry['latency']['p95_ms'], 2)} ms at the 95th percentile. F1 per language:",
            "",
            *language_table(entry),
            "",
            "Taiwan vocabulary is FLORES Simplified text converted with OpenCC `s2twp`, not text "
            "written in Taiwan. FLORES-200 has no romanized Hindi or Urdu, so those are scored on "
            "the Dakshina test files.",
            "",
            "Where the confusion groups go wrong:",
            "",
            *confusion_tables(entry),
            "Accuracy and coverage at each confidence threshold, which is how "
            "`LANGID_MIN_CONFIDENCE` was set:",
            "",
            *threshold_table(entry),
            "",
        ]
    if rag:
        lines += ["### Retrieval and answers", ""] + rag_tables(*rag)
    return "\n".join(lines).strip() + "\n"


def replace_block(readme: str, block: str) -> str:
    start, end = readme.find(START), readme.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"README.md needs the {START} and {END} markers, in that order")
    return readme[:start] + START + "\n\n" + block.strip() + "\n\n" + readme[end:]


def _load(pattern: str) -> tuple[dict, str] | None:
    path = latest(pattern, RESULTS_DIR)
    return (json.loads(path.read_text(encoding="utf-8")), f"results/{path.name}") if path else None


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--detector", default=DEFAULT_DETECTOR)
    args = parser.parse_args()
    block = render(_load("langid-eval-*.json"), _load("rag-eval-*.json"), detector=args.detector)
    README.write_text(
        replace_block(README.read_text(encoding="utf-8"), block), encoding="utf-8", newline="\n"
    )
    print(f"Wrote the results block in {README.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
